def gen_code_sha256(root: Path = REPO) -> dict[str, str]:
    """{repo-relative path: sha256} of the generation code in this checkout: in the job identity,
    so a resume or a recheck by other code is refused, and coverage requires one digest per variant."""
    return {rel: sha256_file(Path(root) / rel) for rel in GEN_CODE}


def mode_problems(a: argparse.Namespace) -> list[str]:
    out = []
    canary_flags = (("--extend-cap", a.extend_cap), ("--repeat-longest", a.repeat_longest),
                    ("--teacher-force-of", a.teacher_force_of))
    if a.mode == "job":
        out += [f"{flag} is not allowed in job mode" for flag, v in (
            ("--cap", a.cap), ("--reverse", a.reverse), ("--model-path", a.model_path),
            ("--probe-longest", a.probe_longest), *canary_flags) if v]
        if a.sample is not None and a.recheck_of is None:
            out.append("--sample is not allowed in job mode (except with --recheck-of)")
        if a.engine not in (None, "vllm"):
            out.append(f"--engine {a.engine} is not allowed in job mode (vllm only)")
        if (a.quant, a.dtype) != ("nf4", "bfloat16"):
            out.append("--quant/--dtype are locked to nf4/bfloat16 in job mode")
        if a.variant == "gen_canary":
            out.append("--variant gen_canary is not a job variant (canary mode only)")
    if a.mode == "canary":
        if a.variant != "gen_canary":
            out.append(f"canary mode writes variant 'gen_canary' only, not {a.variant!r}")
        if set(a.partitions) & {"test", "aux_test"} and not a.probe_longest:
            out.append("canary mode reads test/aux_test prompts only with --probe-longest (which writes no text)")
    if a.mode == "test" and a.variant != "gen_canary" and os.environ.get(TEST_JOB_VARIANTS) != "1":
        out.append(f"--mode test does not write job variant {a.variant!r} (only the test suite sets "
                   f"{TEST_JOB_VARIANTS}=1); use --mode job")
    if a.mode == "test" and set(a.partitions) & {"test", "aux_test"} and os.environ.get(TEST_JOB_VARIANTS) != "1":
        out.append(f"--mode test does not generate from test/aux_test prompts (only the test suite sets "
                   f"{TEST_JOB_VARIANTS}=1): test text comes from job mode")
    if a.mode in ("job", "canary") and not a.gpu_name:
        out.append(f"--gpu-name is required in {a.mode} mode")
    elif a.mode in ("job", "canary"):
        out += [f"--gpu-name: {p}" for p in card_problems(a.gpu_name)]
    if a.mode in ("job", "canary") and a.weights != "base" and not a.adapter_config_sha256:
        out.append(f"--adapter-config-sha256 (the sha256 of the adapter's adapter_config.json) is required in {a.mode} "
                   f"mode")
    if a.mode == "job" and not a.decision_sha256:
        out.append("--decision-sha256 (the variant's decision file, written by genqueue) is required in job mode")
    if a.mode == "job" and not tokenizes_like_training(a.pin_set) and not a.ids_sha256:
        out.append(f"--pin-set {a.pin_set} tokenizes with other versions than training: --ids-sha256 (the laptop's "
                   f"digest of the job's prompt ids) is required in job mode")
    if a.recheck_of is not None and a.sample is None:
        out.append("--recheck-of needs --sample")
    if a.teacher_force_of is not None and (a.engine != "hf" or a.weights == "base"):
        out.append("--teacher-force-of scores an adapter run with --engine hf")
    if (a.extend_cap or a.repeat_longest) and (a.weights == "base" or a.sample is None):
        out.append("--extend-cap and --repeat-longest are for an adapter canary run with --sample")
    return out


def probe_budget(prompt_len: int, window: int, cap: int | None) -> int:
    """The canary probe fills the whole window (prompt + budget = max_model_len), the worst case any real pair can
    reach, instead of stopping at the 6,144 cap."""
    return window - prompt_len if cap is None else min(cap, window - prompt_len)


def open_engine(kind: str, spec, a: argparse.Namespace, window: int, eos_id: int):
    """The engine of the job (tests replace this function to prove no engine loads)."""
    path, revision = a.model_path or spec.hf_id, None if a.model_path else spec.revision
    if kind == "vllm":
        from .engines import VLLMCfg, VLLMEngine

        return VLLMEngine(VLLMCfg(path, revision, window, eos_id, gpu_memory_utilization=a.gpu_memory_utilization,
                                  enforce_eager=a.enforce_eager, lora_input_sizes=LORA_INPUT_SIZES[a.model]),
                          a.adapter)
    from .engines import HFEngine, load_hf

    return HFEngine(load_hf(path, revision, a.quant, a.dtype, a.adapter), eos_id,
                    {"model": path, "quant": a.quant, "dtype": a.dtype, "adapter": None if a.adapter is None
                     else str(a.adapter)})


def _window(spec, model_path: str | None) -> int:
    if not model_path:
        return spec.window
    from transformers import AutoConfig

    return AutoConfig.from_pretrained(model_path).max_position_embeddings


def job_engine_settings(model: str, model_path, window: int, gpu_memory_utilization: float, enforce_eager: bool,
                        engine: str) -> dict:
    """The vLLM settings of a job's identity (without the model path): pinned kwargs, memory steps and, for vLLM, the
    engine route; genqueue computes the same on the laptop to bind the canary's engine."""
    from . import engines
    from .engines import VLLMCfg, vllm_kwargs

    spec = MODELS[model]
    settings = vllm_kwargs(VLLMCfg(model_path or spec.hf_id, None if model_path else spec.revision, window, 0,
                                   gpu_memory_utilization=gpu_memory_utilization, enforce_eager=enforce_eager))
    settings.pop("model")
    if engine == "vllm":        # the engine route decides the numbers too; no absolute path (cross-pod)
        settings.update(batch_invariant=engines.BATCH_INVARIANT, tuned_config_files=engines.tuned_config_files(),
                        env={k: v for k, v in engines.VLLM_ENV.items() if k != "VLLM_TUNED_CONFIG_FOLDER"})
    return settings


def _identity(a: argparse.Namespace, engine: str, prep, ids_sha256: str, window: int) -> dict:
    spec = MODELS[a.model]
    settings = job_engine_settings(a.model, a.model_path, window, a.gpu_memory_utilization, a.enforce_eager, engine)
    meta = prep.prompts_meta.get("meta")
    return {"schema": JOB_SCHEMA, "model": a.model, "weights": a.weights, "variant": a.variant,
            "partitions": sorted(a.partitions), "subset": a.subset, "mode": a.mode,
            "runs": sorted({p.run.condition for p in prep.pairs}), "adapter_tensor_sha256": a.adapter_sha256,
            "adapter_config_sha256": a.adapter_config_sha256,
            "leakcheck_receipt_sha256": a.leakcheck_receipt_sha256, "prompts": dict(sorted(prep.files.items())),
            "prompts_sums_sha256": prep.prompts_meta["sums_sha256"], "ids_sha256": ids_sha256,
            "engine": engine, "engine_settings": settings if engine == "vllm" else
            {"model": a.model_path or spec.hf_id, "quant": a.quant, "dtype": a.dtype}, "window": window,
            "cap": a.cap, "gpu_name": a.gpu_name, "pin_set": a.pin_set, "sample": a.sample, "reverse": a.reverse,
            "recheck_of": None if a.recheck_of is None else str(a.recheck_of), "probe_longest": a.probe_longest,
            "pod_id": os.environ.get("RUNPOD_POD_ID"), "extend_cap": a.extend_cap,
            "model_path": None if a.model_path is None else str(a.model_path), "gen_code_sha256": gen_code_sha256(),
            "compose": meta.get("compose") if isinstance(meta, dict) else None,
            "decision_sha256": a.decision_sha256,
            "repeat_longest": a.repeat_longest,
            "teacher_force_of": None if a.teacher_force_of is None else str(a.teacher_force_of)}


def _core(identity: dict) -> dict:
    return {k: v for k, v in identity.items() if k not in NOT_IDENTITY}


def _write_json(path: Path, obj) -> None:
    """Through a temporary file and os.replace: a kill leaves the old file or the new one."""
    tmp = path.with_name(path.name + ".tmp")
    with tmp.open("w") as f:
        f.write(json.dumps(obj, indent=2, sort_keys=True, default=str))
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def _produced(workdir: Path) -> str:
    """What a run of the workdir's job produced besides outputs.jsonl: "" if nothing."""
    if (workdir / "canary_ids.jsonl").exists():
        return "canary_ids.jsonl"
    try:
        rc = json.loads((workdir / "receipt-generate.json").read_text())
    except (OSError, ValueError):
        return ""
    if not isinstance(rc, dict):
        return ""
    found = [what for what, yes in (("a DONE receipt", rc.get("status") == "DONE"), ("probe results", "probe" in rc),
                                    ("teacher-force results", "hf_agreement" in rc)) if yes]
    return ", ".join(found)


def _read_lines(path: Path) -> dict:
    return {row_key(json.loads(line)): (line + "\n").encode("utf-8") for line in jsonl_lines(path) if line.strip()}


def round_robin_records(record_ids, n: int) -> list[str]:
    """smoke.sample's rule: round robin over repos (record id prefix), each repo in record-id order."""
    return [e.record_id for e in sample([SimpleNamespace(record_id=r) for r in sorted(set(record_ids))], n)]


def select_pairs(pairs: list, budget: dict, n: int, rule: str, original: dict | None = None) -> tuple[list, dict]:
    """The pre-declared sample of a canary run (rule "canary") or a recheck (rule "recheck"); see the docstring."""
    def key(p):
        return p.record_id, p.run.condition

    plen = {key(p): len(budget[(p.record_id, p.run.fmt)][0]) for p in pairs}
    records = round_robin_records([p.record_id for p in pairs], n)
    info: dict = {"rule": rule, "n": n, "records": records}
    if rule == "canary":
        longest_of: dict[str, int] = {}
        for p in pairs:
            longest_of[p.record_id] = max(longest_of.get(p.record_id, 0), plen[key(p)])
        info["longest"] = sorted(longest_of, key=lambda r: (-longest_of[r], r))[:CANARY_LONGEST]
        f2 = [p for p in pairs if p.run.condition == "full_aware"]
        info["longest_f2"] = min(f2, key=lambda p: (-plen[key(p)], p.record_id)).record_id if f2 else None
        keep = set(records) | set(info["longest"]) | {info["longest_f2"]}
        return [p for p in pairs if p.record_id in keep], info
    chosen = {key(p) for p in pairs if p.record_id in set(records)}
    longest = min(pairs, key=lambda p: (-plen[key(p)], p.record_id, p.run.condition))
    info["longest"] = list(key(longest))
    chosen.add(key(longest))
    info["length"] = []
    variant = _variant_of(original)
    for p in sorted(pairs, key=key):
        line = (original or {}).get((p.record_id, p.run.model, p.run.seed, p.run.condition, variant))
        if len(info["length"]) < RECHECK_LENGTH_PAIRS and line is not None and key(p) not in chosen and \
                json.loads(line)["finish_reason"] == "length":
            chosen.add(key(p))
            info["length"].append(list(key(p)))
    return [p for p in pairs if key(p) in chosen], info


def _variant_of(lines: dict | None) -> str | None:
    return next(iter(lines))[4] if lines else None


def select_hf_pairs(rows: list[dict]) -> dict:
    """The 5 full_aware pairs of an adapter canary run scored by the teacher-forced HF check (decision of 24/09): the
    longest prompt; a pair that hit the cap (finish "length"), or, if the run has none, the longest output (the verdict
    then says "no cap-hit pair found"); the rest round robin over repos in record-id order."""
    f2 = sorted((r for r in rows if r["condition"] == "full_aware"), key=lambda r: r["record_id"])
    if not f2:
        return {"keys": [], "cap_hit_found": False, "rule": "no full_aware pair"}
    chosen = [min(f2, key=lambda r: (-r["prompt_tokens"], r["record_id"]))]
    caps = [r for r in f2 if r["finish_reason"] == "length"]
    if caps:
        if chosen[0] not in caps:
            chosen.append(caps[0])
    else:
        longest_out = min(f2, key=lambda r: (-r["new_tokens"], r["record_id"]))
        if longest_out not in chosen:
            chosen.append(longest_out)
    by_id = {r["record_id"]: r for r in f2}
    for rid in round_robin_records([r["record_id"] for r in f2 if r not in chosen], len(f2)):
        if len(chosen) >= HF_PAIRS:
            break
        chosen.append(by_id[rid])
    return {"keys": [list(row_key(r)) for r in chosen], "cap_hit_found": bool(caps),
            "rule": "longest prompt; a cap-hit pair (else the longest output); the rest round robin"}


def build_parser() -> argparse.ArgumentParser:
    """The job's command line; genqueue parses the commands it writes with it."""
    ap = argparse.ArgumentParser(prog="python -m v2gpu.generate", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", required=True, choices=sorted(MODELS))
    ap.add_argument("--weights", required=True, help="'base' or the seed label of the adapter (s42, s11, s23, s7, s99)")
    ap.add_argument("--adapter", type=Path, help="the adapter directory the train receipt selected (adapter weights)")
    ap.add_argument("--adapter-sha256", help="selected_adapter.tensor_sha256 of the train receipt (in the job command)")
    ap.add_argument("--adapter-config-sha256", help="sha256 of the adapter's adapter_config.json (job command)")
    ap.add_argument("--variant", required=True, type=variant_arg, help="a label runs.variant_spec resolves")
    ap.add_argument("--partitions", nargs="+", required=True, help="the partitions the prompt lines must belong to")
    ap.add_argument("--prompts", type=Path, nargs="+", required=True)
    ap.add_argument("--prompts-sums", type=Path, required=True)
    ap.add_argument("--subset", default="all", choices=["all", "lc600", "lc1200"], help="the retrieval pool")
    ap.add_argument("--leakcheck-receipt", type=Path, required=True)
    ap.add_argument("--leakcheck-receipt-sha256", required=True, help="written into the job command on the laptop")
    ap.add_argument("--workdir", type=Path)
    ap.add_argument("--mode", default="job", choices=["job", "canary", "test"])
    ap.add_argument("--engine", choices=["vllm", "hf"], help="default: vllm (job, canary), hf (test)")
    ap.add_argument("--gpu-name", help="the card class of every output, e.g. 'NVIDIA RTX A4000' (job, canary)")
    ap.add_argument("--gpu-memory-utilization", type=float, default=DETERMINISM_STEP[0], choices=GPU_MEMORY_UTILIZATION,
                    help="memory step chosen at the canary (decision 05/10: 0.95 with --enforce-eager for every job)")
