"""One generation job: one model, one weights source (base or one seed's adapter), every planned condition of
those weights on the expected partitions, one engine load.

env HF_HUB_OFFLINE=1 HF_HOME=/opt/v2/hf python -m v2gpu.generate --model deepseek --weights s42
    --adapter RUN/epoch-3 --adapter-sha256 <train receipt digest> --variant main --partitions test aux_test
    --prompts P/deepseek.all.test.F0.jsonl ... --prompts-sums P/PROMPTS_SHA256SUMS
    --leakcheck-receipt R/leakcheck-receipt.deepseek.json --leakcheck-receipt-sha256 <sha>
    --gpu-name "NVIDIA RTX A4000" --workdir runs/gen-main-deepseek-s42

- main() sets HF_HUB_OFFLINE=1 before anything imports huggingface_hub: weights and tokenizers come from the
  checked HF cache only (genqueue also writes `env HF_HUB_OFFLINE=1` into every job command).
- Inputs: prompt files only (answer = null for test/aux; no records, catalog or forbidden.json), checked by
  genprep.preflight, including the laptop leak-audit receipt whose sha256 is in the command (QUEUE.json).
- Modes:
  - `job` (default) locks everything that decides the outputs: engine vLLM (engines.VLLMEngine settings),
    max_new_tokens = min(6,144, window - prompt), no --cap/--reverse/--model-path/--probe-longest or canary flags,
    --sample only with --recheck-of, a real variant (any label runs.variant_spec resolves but gen_canary),
    --gpu-name required and checked (one 16 GB card class of engines.CARD, a tuned LoRA shrink file for that card
    name), the generation venv pins checked against --pin-set (engines.PIN_SETS; default "main").
  - The canary's choices (decision 24/09), written into every job command by genqueue from the canary verdict and
    recorded in the job identity: --gpu-memory-utilization (0.92, or the pre-declared 0.95), --enforce-eager (the
    other pre-declared memory step) and --pin-set. The prefill chunk has no option (engines.PREFILL_CHUNK). A pin set
    whose transformers/tokenizers differ from training's needs --ids-sha256 (the laptop's digest of the job's prompt
    ids) in job mode; whenever --ids-sha256 is given, other ids refuse the job (REFUSED_PREFLIGHT).
  - `canary` (variant gen_canary) allows the canary flags, --sample, --reverse, --cap and the HF reference engine,
    with the same card and pin checks. It may read test/aux_test prompts only with --probe-longest, which writes no
    text.
  - `test` (CPU tests) allows everything, but writes a job variant only when V2GPU_TEST_JOB_VARIANTS=1 (set by
    tests_gpu/conftest.py), so an operator cannot produce "main" lines outside job mode; nor, with any
    variant, text from test/aux_test prompts.
- Output: WORKDIR/outputs.jsonl, one line per (record, run) in the output schema (runs.OUTPUT_FIELDS), appended and
  fsynced line by line (outlog.OutputLog). A rerun resumes: lines already written are checked against this job (every
  fixed field, and in job mode the budget rule) and skipped, a torn last line is cut; a pair is never written twice.
  WORKDIR/job.json holds the job's identity (every input digest and setting, and the pod id); a workdir holding another
  job's outputs, or files and no job.json, is refused and left untouched (job.json may change while no output exists,
  e.g. after a refused preflight); outputs written on another pod are refused (one pod per volume path).
  The workdir is locked (flock) for the whole job: the same job started twice is refused before it touches the running
  job's files. A rerun of a DONE job whose outputs still match the receipt exits 0 without loading an engine.
  Also:
  - ALREADY_DONE needs the receipt's identity to equal this job's; a workdir whose job.json names another job and
    that holds that job's finished run without outputs.jsonl (a DONE receipt, probe or teacher-force results, or
    canary_ids.jsonl) is refused, where it used to report ALREADY_DONE for the new job;
  - the identity's engine_settings hold the engine route too: batch_invariant, VLLM_ENV without the checkout path, and
    the sha256 of the tuned shrink files, so a resume across a route flip is refused;
  - job.json and the receipt are written through a temporary file and os.replace; the receipt is written again
    right after environment() and after the engine starts, so a killed attempt names its engine;
  - canary_ids.jsonl: a pair's ids are appended after its output line, and a torn last line is cut on resume;
  - with nothing left to generate no engine loads, and the receipt keeps the engine of the attempt that generated the
    lines (engine_from); repeat_in_process says whether the repeated pair was generated by this process.
  The identity also holds model_path (a local snapshot never shares an identity with the hub model) and
  gen_code_sha256 (GEN_CODE, every v2gpu module this job loads); the route fields read config/lora_ops for the vLLM
  engine only, and a missing folder is REFUSED_ENVIRONMENT; a stale *.tmp of a killed first write is not content;
  the compose block of PROMPTS_META.json (compose); build_parser() is the command line genqueue parses.
  --gpu-name is one of engines.CARD; job mode requires --decision-sha256 (the variant's decision
  file, written by genqueue), which the identity keeps; job_engine_settings() is the settings part of the identity.
  An adapter job also requires --adapter-config-sha256 (the sha256 of adapter_config.json,
  checked against the file by engines.adapter_problems and kept in the identity); the receipt's environment records
  the requirements locks, the driver and the numerics env vars (receipt.environment).
- Determinism check of real outputs: --recheck-of DIR --sample N (allowed in job mode) regenerates, in a
  fresh process, a pre-declared set of pairs of the finished job DIR (its receipt DONE and its outputs_sha256 matching)
  and compares the lines byte for byte. The set: every pair of N records chosen round robin over repos,
  PLUS the pair with the job's longest prompt, PLUS up to two pairs whose original line finished "length" (the first
  two in key order). The recheck may run on another pod (a copy of DIR): the receipt records both pod ids.
- Canary (decision 24/09), all in canary mode on dev prompts:
  - --sample N: the pairs of N round-robin records PLUS the records of the 3 longest prompts of the job PLUS the
    record of the job's longest full_aware (F2) prompt, where select_hf_pairs starts (decision 24/09);
  - --extend-cap LIMIT (adapter weights): if no full_aware pair of the run finished "length", further records in
    round-robin order get their full_aware pair generated until one does or the run holds LIMIT records;
  - --repeat-longest R (adapter weights): the full_aware pair with the longest output is regenerated R times in this
    process; the receipt records whether all R are identical to the first;
  - canary (and test) runs write WORKDIR/canary_ids.jsonl (the generated token ids of every pair);
  - --teacher-force-of A (engine hf): no generation; the 5 full_aware pairs of the adapter run A chosen by
    select_hf_pairs are scored under the HF model (engines.teacher_forced_agreement) and the receipt records the
    agreement per pair and overall;
  - --probe-longest: the longest prompt of the job generates until the sequence fills the whole window
    (max_model_len; EOS ignored), the worst case any real pair can reach; the receipt records the peak CUDA memory and
    the speed. No output line is written.
The receipt records code_sha256 (audit.code_sha256: the code that decides a leak audit, as this checkout has it), so
coverage binds the leak receipts to the code that generated.
Exit codes: 0 DONE, 2 refused (settings, inputs, workdir, outputs, card or venv; nothing generated), 1 crash, incomplete
run, recheck mismatch or short probe. Every exit after the workdir check leaves receipt-generate.json.
"""
