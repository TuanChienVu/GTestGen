SHA256 = re.compile(r"[0-9a-f]{64}")


def _listed(n: int, keys) -> dict:
    return {"n": n, "first": [list(k) for k in sorted(keys)[:FIRST]]}


def _json(path: Path):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return None


def _attempt_num(path: Path) -> int:
    return int(path.stem.rsplit("-", 1)[-1])


def job_attempts(workdir: Path) -> list[dict]:
    """For the run manifest of 3C/3D: the chronological attempts of a gen job, [{"file", "status", "sha256"}] --
    every archived receipt-generate.attempt-K.json in order, then the current receipt-generate.json if present. An
    unreadable file still gets an entry (status None), so a torn or missing JSON is evidence too, not silently
    dropped; a workdir with neither gives []."""
    workdir = Path(workdir)
    out = []
    for p in sorted(workdir.glob("receipt-generate.attempt-*.json"), key=_attempt_num):
        r = _json(p)
        out.append({"file": p.name, "status": (r or {}).get("status") if isinstance(r, dict) else None,
                    "sha256": sha256_file(p)})
    cur = workdir / "receipt-generate.json"
    if cur.is_file():
        r = _json(cur)
        out.append({"file": cur.name, "status": (r or {}).get("status") if isinstance(r, dict) else None,
                    "sha256": sha256_file(cur)})
    return out


def job_identity(workdir: Path) -> dict | None:
    """For the run manifest: the identity of a gen-* job, read from its current receipt or, failing that, its
    latest archived attempt -- so a workdir whose LAST attempt crashed before writing a fresh receipt (leaving only
    receipt-generate.attempt-K.json files behind) can still be matched to the (model, weights) pair it belongs to."""
    workdir = Path(workdir)
    candidates = [workdir / "receipt-generate.json",
                 *sorted(workdir.glob("receipt-generate.attempt-*.json"), key=_attempt_num, reverse=True)]
    for p in candidates:
        r = _json(p)
        if isinstance(r, dict) and isinstance(r.get("identity"), dict):
            return r["identity"]
    return None


def _copy_time(w: Path) -> str:
    """The chronological key for ordering the --lost-workdirs copies of
    the SAME (model, weights) job. Sorting by the copy's leaf folder name (the old rule) silently fell back to
    argument order in the real, NESTED copy layout (results-lost/<job>.a<timestamp>/.../<job>): every copy's
    leaf is always the bare job name, so every copy tied and Python's stable sort just kept the caller's own order --
    exactly the accident a reproduction showed (a wrong "last" status, evidence_eligible true when it should be
    false). Read instead each copy's OWN receipts (its archived attempts in order, then its current receipt): the
    latest finished_utc (else started_utc) among them, so a crashed or unreadable current receipt still yields the
    last attempt's own time. "" (sorts first, oldest) when a copy has no readable timestamp at all -- the caller's
    own w.name tiebreak then falls back to the pre-fix behaviour for such a copy, never a crash."""
    latest = ""
    candidates = (*sorted(w.glob("receipt-generate.attempt-*.json"), key=_attempt_num), w / "receipt-generate.json")
    for p in candidates:
        r = _json(p)
        if isinstance(r, dict):
            t = r.get("finished_utc") or r.get("started_utc")
            if isinstance(t, str) and t:
                latest = t
    return latest


def lost_evidence(paths, variant: str) -> dict[tuple, dict]:
    """For the run manifest ("Evidence from failed jobs"): {(model, weights): {"workdir", "attempts"}} of every
    --lost-workdirs directory identified as a gen job (never a recheck) of this variant. Used for evidence only: a
    --lost-workdirs line is never a source of scored output lines (its outputs.jsonl, if any, is not read here).
    A job can come home as MULTIPLE --lost-workdirs directories, one per
    retried attempt (GEN §7 copies each failed attempt to a fresh name, never overwriting or skipping the earlier
    one). Every directory of the SAME (model, weights) is merged here -- a union of their attempts by sha256,
    de-duplicated with _dedupe_attempts and ordered by each copy's own receipt time, name only as the tiebreak
    (name alone ties on every copy of the real, nested layout) -- instead of
    keeping only the last
    directory the caller happened to list last: before this fix, `out[key] = {...}` simply overwrote any earlier
    directory of the same pair, so which directory --lost-workdirs listed LAST silently decided the recorded
    attempt count (and therefore evidence_eligible)."""
    by_pair: dict[tuple, list[Path]] = {}
    for w in map(Path, paths):
        ident = job_identity(w)
        if ident is None or ident.get("recheck_of") or ident.get("variant") != variant:
            continue
        by_pair.setdefault((ident.get("model"), ident.get("weights")), []).append(w)
    out = {}
    for key, ws in by_pair.items():
        # Ordered by each copy's own receipt time first (see _copy_time), name only as the
        # tiebreak -- name alone (the old rule) ties on every copy of the real, nested layout.
        ws = sorted(ws, key=lambda w: (_copy_time(w), w.name))
        attempts = _dedupe_attempts([a for w in ws for a in job_attempts(w)])
        out[key] = {"workdir": ws[-1].name, "attempts": attempts}
    return out


def _dedupe_attempts(attempts: list[dict]) -> list[dict]:
    """A job given to BOTH --workdirs and --lost-workdirs (an operator mistake,
    or a job moved but the old path also kept around) reads the SAME receipt files from both sources, so the naive
    concatenation counted one real attempt twice. The evidence rule's ">= 2 attempts" must count DISTINCT receipts:
    de-duplicate by sha256, keeping the first occurrence's position (chronological: --lost-workdirs' attempts
    precede results/'s own, per _missing_row)."""
    seen, out = set(), []
    for a in attempts:
        if a["sha256"] in seen:
            continue
        seen.add(a["sha256"])
        out.append(a)
    return out


def evidence_eligible(receipt_status: str | None, attempts: list[dict]) -> bool:
    """The evidence rule: a missing row's job may be accepted ONLY when its
    (last attempt's) receipt is CRASHED or INCOMPLETE and the SAME job has at least 2 attempts that each read as a
    receipt (a status, not just an unreadable file). REFUSED_* and absent never qualify."""
    if receipt_status not in ("CRASHED", "INCOMPLETE"):
        return False
    return sum(a["status"] is not None for a in attempts) >= 2


def _differing(prints: list) -> list[str]:
    """The fingerprint keys (key.subkey inside dicts) whose values are not the same in every fingerprint; a record
    without a fingerprint (None: it names no engine) is left out here and reported by workdir_problems."""
    out = []
    prints = [fp for fp in prints if isinstance(fp, dict)]
    for k in sorted({k for fp in prints for k in fp}):
        values = [fp.get(k) for fp in prints]
        if all(isinstance(v, dict) for v in values):
            out += [f"{k}.{kk}" for kk in sorted({kk for v in values for kk in v})
                    if len({json.dumps(v.get(kk), sort_keys=True) for v in values}) > 1]
        elif len({json.dumps(v, sort_keys=True) for v in values}) > 1:
            out.append(k)
    return out


def workdir_problems(workdirs, variant: str, sample: int = 5) -> tuple[list[str], list, list, dict, dict | None, dict]:
    """(problems, gen workdirs, recheck workdirs, cross-pod by model, the code_sha256 that generated, the compose
    blocks by workdir) from the receipts of the copied-home workdirs."""
    problems, gens, rechecks, prints, codes, gen_codes, composes = [], [], [], {}, {}, {}, {}
    for w in map(Path, workdirs):
        rc = _json(w / "receipt-generate.json")
        if not isinstance(rc, dict):
            problems.append(f"{w.name}: no readable receipt-generate.json")
            continue
        ident = rc.get("identity") if isinstance(rc.get("identity"), dict) else {}
        where = f"{w.name}"
        if rc.get("status") != "DONE":
            problems.append(f"{where}: receipt status {rc.get('status')!r}, not DONE")
        if rc.get("mode") != "job":
            problems.append(f"{where}: written in {rc.get('mode')!r} mode, not job mode")
        if ident.get("engine") != "vllm":
            problems.append(f"{where}: engine {ident.get('engine')!r}, not vllm")
        if ident.get("variant") != variant:
            problems.append(f"{where}: variant {ident.get('variant')!r}, not {variant!r}")
        out = w / "outputs.jsonl"
        if not out.exists() or rc.get("outputs_sha256") != sha256_file(out):
            problems.append(f"{where}: outputs.jsonl does not match the receipt's outputs_sha256")
        packages = (rc.get("environment") or {}).get("packages") or {}
        problems += [f"{where}: {p}" for p in pin_problems(packages, ident.get("pin_set"))]
        engine = rc.get("engine") if isinstance(rc.get("engine"), dict) else {}
        codes[w.name] = json.dumps(rc.get("code_sha256"), sort_keys=True)
        gen_codes[w.name] = json.dumps(ident.get("gen_code_sha256"), sort_keys=True)
        composes[w.name] = ident.get("compose")
        fingerprint = engine_fingerprint(engine)
        why = engine_record_problems(rc.get("engine") if rc.get("engine") is not None else {})
        if why:                                  # a problem, not a TypeError in _differing
            problems.append(f"{where}: the receipt's engine record gives no engine fingerprint: {'; '.join(why)}")
        prints[w.name] = (ident.get("gpu_name"), fingerprint, engine.get("batch_invariant"), ident.get("pin_set"))
        (rechecks if ident.get("recheck_of") else gens).append((w, rc))
    if len({p[0] for p in prints.values()}) > 1:
        problems.append(f"workdirs name several cards (gpu_name): {sorted({str(p[0]) for p in prints.values()})}")
    problems += [f"workdirs: {p}" for p in sorted({p for pr in prints.values() for p in card_problems(pr[0])})]
    if len({p[3] for p in prints.values()}) > 1:
        problems.append(f"workdirs mix pin sets {sorted({str(p[3]) for p in prints.values()})}: one pin set for the "
                        f"variant, chosen at the canary")
    if len({p[2] for p in prints.values()}) > 1:
        problems.append("workdirs mix batch_invariant true and false (route (b) and fallback (a)); never mixed")
    code = None
    if len(set(codes.values())) > 1 or "null" in codes.values():
        problems.append("workdirs were generated by different code (code_sha256: the leak rules and the audit "
                        "modules), or name none: one code_sha256 for the variant")
    elif codes:
        code = json.loads(next(iter(codes.values())))
    if len(set(gen_codes.values())) > 1 or "null" in gen_codes.values():
        problems.append("workdirs were generated by different generation code (identity.gen_code_sha256), or name "
                        "none: one gen_code_sha256 for the variant")
    differ = _differing([p[1] for p in prints.values()])
    if differ:
        problems.append(f"workdirs differ in the engine (engines.engine_fingerprint): {', '.join(differ)}; one engine "
                        f"for the variant")
    good = {}
    for w, rc in rechecks:
        rk = rc.get("recheck") or {}
        got = ((rc.get("identity") or {}).get("sample"), (rc.get("sample") or {}).get("n"))
        if got != (sample, sample):
            problems.append(f"{w.name}: recheck sample {got[0]!r} (receipt sample.n {got[1]!r}), not the declared "
                            f"--recheck-sample {sample}")
        elif rc.get("status") == "DONE" and rk.get("identical") is True:
            good.setdefault(rk.get("of_outputs_sha256"), []).append((rc.get("pod_id"), rk.get("of_pod_id")))
    cross: dict = {}
    for w, rc in gens:
        found = good.get(rc.get("outputs_sha256"), [])
        if not found:
            problems.append(f"{w.name}: no DONE recheck with identical outputs")
        model = (rc.get("identity") or {}).get("model", "?")
        cross[model] = cross.get(model, False) or any(p and o and p != o for p, o in found)
    if variant != "gen_canary":         # decision 25/09: the dev pilot, then every real variant
        problems += [f"no cross-pod recheck for {m} (a recheck on another pod than its job)" for m, ok in
                     sorted(cross.items()) if not ok]
    return problems, gens, rechecks, dict(sorted(cross.items())), code, composes


def decision_record(path: Path | None) -> dict:
    """The card class, the pin set and the decision sha256 of the variant, for the report."""
    d = _json(path) if path is not None else None
    decision = d.get("decision") if isinstance(d, dict) and isinstance(d.get("decision"), dict) else {}
    return {"gpu_name": decision.get("gpu_name"), "pin_set": decision.get("pin_set"),
            "decision_sha256": sha256_file(path) if path is not None and Path(path).is_file() else None}


def lock_of(rc: dict) -> tuple[str, str | None, bool, str | None]:
    """(lock name, sha256, first run, problem) of the generation venv a receipt ran: the committed
    requirements-gen[-<set>].lock of its pin set, or, for the first pod of a KIND, the lock that venv froze
    (environment.first_run_lock). The committed lock comes first. A value under the lock's name that
    is not a 64-hex sha256 ("", "x", a dict) is a problem, never a lock."""
    ident = rc.get("identity") if isinstance(rc.get("identity"), dict) else {}
    pin_set = ident.get("pin_set") or "main"
    name = "requirements-gen.lock" if pin_set == "main" else f"requirements-gen-{pin_set}.lock"
    env = rc.get("environment") if isinstance(rc.get("environment"), dict) else {}
    for source, is_first in (("locks", False), ("first_run_lock", True)):
        table = env.get(source) if isinstance(env.get(source), dict) else {}
        if name not in table:
            continue
        value = table[name]
        if isinstance(value, str) and SHA256.fullmatch(value):
            return name, value, is_first, None
        return name, None, is_first, f"environment.{source} records {name} as {json.dumps(value)[:80]}, not a sha256 " \
                                     f"(64 hex)"
    return name, None, False, None


def lock_problems(workdirs: list) -> tuple[list[str], dict, list[str]]:
    """Every workdir of the variant ran one requirements lock: (problems, {name: sha256}, the
    workdirs that ran a first-run venv, shown in the report)."""
    seen, first, missing, malformed = {}, [], [], []
    for w, rc in workdirs:
        name, sha, is_first, problem = lock_of(rc)
        if problem:
            malformed.append(f"{w.name}: {problem}")
            continue
        if sha is None:
            missing.append(w.name)
            continue
        seen.setdefault((name, sha), []).append(w.name)
        if is_first:
            first.append(w.name)
    out = malformed + ([f"{len(missing)} workdirs record no requirements lock and no first-run lock (e.g. "
                        f"{', '.join(sorted(missing)[:3])}): a pod installs the committed lock, only the first pod "
                        f"freezes one"] if missing else [])
    if len(seen) > 1:
        out.append(f"workdirs ran several requirements locks: {sorted(f'{n} {s[:12]}' for n, s in seen)}; one lock "
                   f"for the variant")
    return out, {n: s for n, s in seen}, sorted(first)


def decision_problems(path: Path, variant: str, workdirs: list) -> list[str]:
    """Every workdir of the variant ran its decision: identity.decision_sha256 is the
    sha256 of --decision, and the code, declared engine, card, pin set and measured engine are the decision's."""
    d = _json(path)
    if not isinstance(d, dict) or d.get("schema") != DECISION_SCHEMA or d.get("pass") is not True or \
            not isinstance(d.get("decision"), dict):
        return [f"{path}: not a passing {DECISION_SCHEMA} decision file (gencanary decide)"]
    out = [] if d.get("variant") == variant else [
        f"{path}: the decision of variant {d.get('variant')!r}, not {variant}"]
    out += [f"{path}: the decision fails the pre-declared orders (card gpu_name, pin set, memory step): {p}"
            for p in decision_value_problems(d["decision"])]
    verdicts = d.get("verdicts") if isinstance(d.get("verdicts"), dict) else {}
    got, planned = sorted(verdicts), planned_models(variant)
    if got != planned:
        out.append(f"{path}: the decision's verdicts {got} do not cover the models {variant} plans {planned}")
    out += verdict_file_problems(path, verdicts, d)
    out += [f"{path}: the decision binds no {k} (gencanary decide copies it from its verdicts)" for k in BINDING
            if d.get(k) is None]
    if variant == "main" and not d.get("prompts_sums_sha256"):
        out.append(f"{path}: main's decision names no prompts_sums_sha256 (the test/aux directory its canaries probed)")
    want = {"decision_sha256": sha256_file(path), "gen_code_sha256": d.get("gen_code_sha256"),
            "engine_settings": d.get("engine_settings"), "pin_set": d["decision"].get("pin_set"),
            "gpu_name": d["decision"].get("gpu_name"), "engine_fingerprint": d.get("engine_fingerprint")}
    differ: dict = {}
    for w, rc in workdirs:
        ident = rc.get("identity") if isinstance(rc.get("identity"), dict) else {}
        engine = rc.get("engine") if isinstance(rc.get("engine"), dict) else {}
        got = {"decision_sha256": ident.get("decision_sha256"), "gen_code_sha256": ident.get("gen_code_sha256"),
               "engine_settings": declared_engine(ident.get("engine_settings") or {}), "pin_set": ident.get("pin_set"),
               "gpu_name": ident.get("gpu_name"), "engine_fingerprint": engine_fingerprint(engine)}
        for k, v in want.items():
            if got[k] != v:
                differ.setdefault(k, []).append(w.name)
    out += [f"{len(names)} workdirs differ from the decision in {k} (e.g. {', '.join(sorted(names)[:3])})"
            for k, names in sorted(differ.items())]
    return out


def verdict_file_problems(path: Path, verdicts: dict, d: dict) -> list[str]:
    """Each canary verdict the decision names, read from its file (a decision naming
    the planned models with empty records, or a fake path with sha256 0...0, passed): the path decide recorded
    (relative to the directory it ran in), the recorded sha256, a passing verdict of that model, holding the decision
    file's decision; and the decision's value of every key of gencanary.BINDING, and in
    its probed_sums the decision's prompts_sums_sha256, so a decision edited by hand to bind another code, engine or
    prompt directory than its verdicts ran is refused."""
    decision, sums, out = d["decision"], d.get("prompts_sums_sha256"), []
    for m, rec in sorted(verdicts.items()):
        where = rec.get("verdict") if isinstance(rec, dict) else None
        if not isinstance(where, str) or not where:
            out.append(f"{path}: the verdict of {m} names no file (decide records its path and sha256)")
            continue
        vpath = Path(where)
        if not vpath.is_file():
            out.append(f"{path}: the verdict of {m}, {where}, is not a file here (run gencoverage in the directory "
                       f"decide ran in)")
            continue
        digest, recorded = sha256_file(vpath), rec.get("sha256")
        if digest != recorded:
            out.append(f"{path}: the verdict of {m}, {where}, has sha256 {digest[:12]}…, the decision recorded "
                       f"{str(recorded)[:12]}…")
            continue
        v = _json(vpath)
        if not isinstance(v, dict):
            out.append(f"{path}: the verdict of {m}, {where}, is not a readable verdict")
            continue
        if v.get("pass") is not True:
            out.append(f"{path}: the verdict of {m}, {where}, is not a passing canary verdict")
        if v.get("model") != m:
            out.append(f"{path}: the verdict of {m}, {where}, is a verdict of {v.get('model')!r}")
        if v.get("decision") != decision:
            out.append(f"{path}: the verdict of {m}, {where}: its canary decision "
                       f"{json.dumps(v.get('decision'), sort_keys=True)} is not the decision file's "
                       f"{json.dumps(decision, sort_keys=True)}")
        out += [f"{path}: the verdict of {m}, {where}: its {k} is not the decision file's (the canary ran another "
                f"code or engine than the decision binds)" for k in BINDING if v.get(k) != d.get(k)]
        if sums is not None and sums not in (v.get("probed_sums") or []):
            out.append(f"{path}: the verdict of {m}, {where}: its probed_sums hold no {str(sums)[:12]}…, the "
                       f"decision's prompts_sums_sha256 (no probe of that canary read that prompt directory)")
    return out


def train_digests(paths, variant: str | None = None, meta=None, pilot_compose: dict | None = None
                  ) -> tuple[list[str], dict]:
    """{(model, seed): selected tensor digest} of the train receipts; with a variant, each adapter's compose is checked
    against the generation META compose (genprep.adapter_compose_problems). For a
    second-round dev grid variant, `pilot_compose` (the round's OWN dev_pilot_vN META compose, read from --dev-pilot-meta)
    is the reference instead, since the grid's own META compose legitimately varies k, n_examples and ratio away from
    it. Every receipt must carry train_code_sha256 and train_cfg_sha256,
    and all of them here (one gencoverage run, one variant) must share one value of each.
    Since 27/09, the cross-adapter agreement is keyed by the adapter
    (model, "s<seed>"), never by path.name -- the real pod layout is results/<model>-s<seed>-all/receipt-train.json,
    so every receipt shares the SAME basename, and a path.name-keyed dict silently kept only the last one read,
    making the whole check vacuous. Every problem also names the adapter, not just the receipt's bare filename."""
    problems, out = [], {}
    codes, cfgs = {}, {}
    for path in map(Path, paths):
        r = _json(path)
        if not isinstance(r, dict) or r.get("status") != "DONE" or r.get("mode") != "job":
            problems.append(f"{path}: not a DONE job-mode train receipt")
            continue
        key = ((r.get("model") or {}).get("key"), f"s{r.get('seed')}")
        label = f"{path} ({key[0]} {key[1]})"
        if r.get("subset") != "all":                   # the scored adapters, pool all
            problems.append(f"{label}: trained on pool {r.get('subset')!r}, not all")
            continue
        if key in out:
            problems.append(f"{label}: a second train receipt for {key[0]} {key[1]}; give one per adapter")
            continue
        out[key] = (r.get("selected_adapter") or {}).get("tensor_sha256")
        if variant is not None:
            compose = (((r.get("data") or {}).get("prompts") or {}).get("meta") or {}).get("compose")
            problems += [f"{label}: {p}" for p in adapter_compose_problems(variant, meta, compose, pilot_compose)]
        train_code = r.get("train_code_sha256")
        if not isinstance(train_code, dict) or not train_code:
            problems.append(f"{label}: no train_code_sha256")
        else:
            codes[key] = json.dumps(train_code, sort_keys=True)
        train_cfg = r.get("train_cfg_sha256")
        if not isinstance(train_cfg, str) or not train_cfg:
            problems.append(f"{label}: no train_cfg_sha256")
        else:
            cfgs[key] = train_cfg
        # Decision 27/09: fp32 upcast is mandatory for every real training job; gencoverage
        # refuses, for every variant, an adapter whose train receipt says otherwise (or omits train_config).
        if (r.get("train_config") or {}).get("upcast_fp32") is not True:
            problems.append(f"{label}: train_config.upcast_fp32 is not true: every real "
                            f"adapter must be trained with --upcast-fp32")
    for field, values in (("train_code_sha256", codes), ("train_cfg_sha256", cfgs)):
        if len(set(values.values())) > 1:
            problems.append(f"{field} differs across adapters of this variant: " +
                            "; ".join(f"{k[0]} {k[1]}={v}" for k, v in sorted(values.items())))
    return problems, out


def train_gpu_names(paths) -> dict[tuple, str | None]:
    """{(model, seed): training GPU name} read from receipt.environment()["device"]["name"]
    of each train receipt (--train-receipts), for the project report (recorded verbatim in coverage.json's "training_gpu").
    Best-effort and read-only: an unreadable or malformed receipt (already a problem elsewhere, from train_digests)
    is simply left out, never a crash here; a receipt with no CUDA device (e.g. a stray CPU run) gives None."""
    out = {}
    for path in map(Path, paths):
        r = _json(path)
        if not isinstance(r, dict):
            continue
        key = ((r.get("model") or {}).get("key"), f"s{r.get('seed')}")
        out[key] = ((r.get("environment") or {}).get("device") or {}).get("name")
    return out


def train_card_problems(gpu_by_adapter: dict) -> list[str]:
    """Since 27/09, card assignment is per SEED -- every model trained at the same
    numeric seed must share one training card class, so the card never confounds the seed-paired comparison across
    models (e.g. deepseek-s42 vs codellama-s42 vs mistral-s42). Adapters with no recorded GPU name (a CPU run, or a
    receipt predating this fix) are left out of the comparison, never flagged on their own."""
    by_seed: dict[str, dict[str, list[str]]] = {}
    for (model, seed), gpu in gpu_by_adapter.items():
        if gpu is not None:
            by_seed.setdefault(seed, {}).setdefault(gpu, []).append(model)
    out = []
    for seed, by_card in sorted(by_seed.items()):
        if len(by_card) > 1:
            detail = "; ".join(f"{card!r}: {', '.join(sorted(models))}" for card, models in sorted(by_card.items()))
            out.append(f"seed {seed}: adapters were trained on different card classes ({detail}); card assignment "
                       f"is per seed (decision 27/09), so this would confound the seed-paired comparison")
    return out


def gen_card_by_pair_problems(gens, rechecks) -> list[str]:
    """Within one (model, seed) adapter, its job and the recheck(s) that verify it must
    record the same gpu_name. The generation card is already required to be one class for the WHOLE variant
    (workdir_problems' "workdirs name several cards"); this names the (model, seed) offenders specifically, e.g.
    after a lost-pod recovery reran a job (or its recheck) on another card. A recheck is matched to its job the same
    way cross-pod evidence is (recheck.of_outputs_sha256 == the job's own outputs_sha256), not by identity.weights,
    which a recheck need not carry."""
    by_pair: dict[tuple, dict[str, list[str]]] = {}
    by_outputs: dict = {}
    for w, rc in gens:
        ident = rc.get("identity") if isinstance(rc.get("identity"), dict) else {}
        key = (ident.get("model"), ident.get("weights"))
        by_outputs[rc.get("outputs_sha256")] = key
        by_pair.setdefault(key, {}).setdefault(ident.get("gpu_name"), []).append(w.name)
    for w, rc in rechecks:
        key = by_outputs.get((rc.get("recheck") or {}).get("of_outputs_sha256"))
        if key is None:
            continue
        ident = rc.get("identity") if isinstance(rc.get("identity"), dict) else {}
        by_pair.setdefault(key, {}).setdefault(ident.get("gpu_name"), []).append(w.name)
    out = []
    for (model, weights), by_card in sorted(by_pair.items(), key=lambda kv: (str(kv[0][0]), str(kv[0][1]))):
        if len(by_card) > 1:
            detail = "; ".join(f"{card!r}: {', '.join(sorted(names))}" for card, names in sorted(
                by_card.items(), key=lambda kv: str(kv[0])))
            out.append(f"{model} {weights}: generation workdirs record different gpu_name across conditions "
                       f"({detail})")
    return out


def leak_receipts(paths, code: dict | None) -> tuple[list[str], dict]:
    """PASS receipts made by `code`, the code_sha256 the generation receipts record."""
    problems, out = [], {}
    for path in map(Path, paths):
        r = _json(path)
        if not isinstance(r, dict):
            problems.append(f"{path.name}: not a leak-audit receipt")
            continue
        if r.get("schema") != LEAKCHECK_SCHEMA or r.get("status") != "PASS" or r.get("n_problems") != 0:
            problems.append(f"{path.name}: not a PASS {LEAKCHECK_SCHEMA} receipt")
        elif code is None or r.get("code_sha256") != code:
            problems.append(f"{path.name} ({r.get('model')}): code_sha256 is not the one that generated the outputs "
                            f"(other leak rules)")
        else:
            out[sha256_file(path)] = r
    return problems, out


MANIFEST_ROW = ("model", "condition", "seed", "variant", "record_id", "fmt", "prompts_sha256", "prompt_sha256",
                "adapter_tensor_sha256", "decision_sha256", "gen_code_sha256", "leakcheck_receipt_sha256", "workdir",
                "receipt_sha256", "outputs_sha256", "line_sha256", "status", "reason", "receipt_status", "attempts",
                "evidence_eligible")


def _manifest_row(run, rid: str, fmt: str, variant: str, status: str, reason=None) -> dict:
    """For the run manifest of 3C/3D: every field of one row, defaulted to null/False; the caller fills in
    whatever `status` (ok/excluded/missing) makes known."""
    return {**dict.fromkeys(MANIFEST_ROW), "model": run.model, "condition": run.condition, "seed": run.seed,
           "variant": variant, "record_id": rid, "fmt": fmt, "status": status, "reason": reason,
           "evidence_eligible": False}


def _ok_row(run, rid: str, fmt: str, variant: str, prompt_hashes: tuple, ev: dict, adapters: dict,
           decision_sha256: str | None) -> dict:
    row = _manifest_row(run, rid, fmt, variant, "ok")
    w, rc = ev["w"], ev["rc"]
    ident = rc.get("identity") if isinstance(rc.get("identity"), dict) else {}
    receipt = w / "receipt-generate.json"
    row.update(prompts_sha256=prompt_hashes[0], prompt_sha256=prompt_hashes[1],
               adapter_tensor_sha256=None if run.seed == "base" else adapters.get((run.model, run.seed)),
               decision_sha256=decision_sha256, gen_code_sha256=ident.get("gen_code_sha256"),
               leakcheck_receipt_sha256=ident.get("leakcheck_receipt_sha256"), workdir=w.name,
               receipt_sha256=sha256_file(receipt) if receipt.is_file() else None,
               outputs_sha256=rc.get("outputs_sha256"), line_sha256=_line_sha256(ev["line"]))
    return row


def _missing_row(run, rid: str, fmt: str, variant: str, prompt_hashes: tuple, adapters: dict,
                 decision_sha256: str | None, gens_by_pair: dict, lost: dict) -> dict:
    """For the run manifest ("Evidence from failed jobs" and the evidence rule): receipt_status/receipt_sha256 are
    the LAST attempt's (results/ wins over --lost-workdirs when both exist for the same job: results/ is where a
    job's current, most recent attempt lives); attempts covers both sources, chronologically (a job moved out of
    results/ into results-lost/ had its earlier attempts there first)."""
    row = _manifest_row(run, rid, fmt, variant, "missing")
    row.update(prompts_sha256=prompt_hashes[0], prompt_sha256=prompt_hashes[1], decision_sha256=decision_sha256,
               adapter_tensor_sha256=None if run.seed == "base" else adapters.get((run.model, run.seed)))
    pair_key = (run.model, run.seed)
    lost_info = lost.get(pair_key)
    attempts = list(lost_info["attempts"]) if lost_info else []
    workdir_name = lost_info["workdir"] if lost_info else None
    receipt_status = attempts[-1]["status"] if attempts else None
    receipt_sha256 = attempts[-1]["sha256"] if attempts else None
    if pair_key in gens_by_pair:
        w, rc = gens_by_pair[pair_key]
        ident = rc.get("identity") if isinstance(rc.get("identity"), dict) else {}
        attempts = attempts + job_attempts(w)                # results/'s own attempts are the later ones
        workdir_name = w.name
        receipt_status = rc.get("status")
        cur = w / "receipt-generate.json"
        receipt_sha256 = sha256_file(cur) if cur.is_file() else (attempts[-1]["sha256"] if attempts else None)
        row.update(gen_code_sha256=ident.get("gen_code_sha256"),
                   leakcheck_receipt_sha256=ident.get("leakcheck_receipt_sha256"))
    if workdir_name is None:
        receipt_status, attempts = "absent", []
    attempts = _dedupe_attempts(attempts)
    row.update(workdir=workdir_name, receipt_status=receipt_status, receipt_sha256=receipt_sha256,
               attempts=attempts, evidence_eligible=evidence_eligible(receipt_status, attempts))
    return row


def _line_sha256(line: str) -> str:
    """For the run manifest: the sha256 of the exact raw bytes of an outputs.jsonl line, without the trailing
    "\\n" -- jsonl_lines already split on "\\n" and dropped it, so `line` here IS that byte span, re-encoded."""
    return hashlib.sha256(line.encode("utf-8")).hexdigest()


def write_manifest(path: Path, variant: str, parts, ids: dict, listed: dict, index: dict, gens_by_pair: dict,
                   lost: dict, seen, evidence: dict, adapters: dict, decision_sha256: str | None) -> str:
    """For the run manifest of 3C/3D: exactly one row per expected pair (runs.planned_runs x the records of the
    prompt files for that variant, i.e. `ids`), one JSON line each (sort_keys), rows sorted by (model, condition,
    seed, record_id, fmt) for a deterministic, byte-identical file across runs. Recheck workdirs are never rows.
    Returns the written file's sha256."""
    rows = []
    for part in parts:
        for run in planned_runs(variant, part):
            for rid in sorted(ids[part]):
                fmt = run.fmt
                key5 = (rid, run.model, run.seed, run.condition, variant)
                if (rid, fmt) in listed[run.model]:
                    rows.append(_manifest_row(run, rid, fmt, variant, "excluded", listed[run.model][(rid, fmt)]))
                elif (run.model, rid, fmt) not in index:
                    continue      # no prompt and no exclusion: already a data-integrity `problems` entry elsewhere
                else:
                    prompt_hashes = index[(run.model, rid, fmt)][1:]
                    if key5 in seen and seen[key5] > 0:
                        rows.append(_ok_row(run, rid, fmt, variant, prompt_hashes, evidence[key5], adapters,
                                            decision_sha256))
                    else:
                        rows.append(_missing_row(run, rid, fmt, variant, prompt_hashes, adapters, decision_sha256,
                                                 gens_by_pair, lost))
    rows.sort(key=lambda r: (r["model"], r["condition"], r["seed"], r["record_id"], r["fmt"]))
    lines = [json.dumps(r, sort_keys=True) for r in rows]
    path.write_text("".join(l + "\n" for l in lines))
    return sha256_file(path)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m v2gpu.gencoverage", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variant", required=True, type=variant_arg, help="a label runs.variant_spec resolves")
    ap.add_argument("--prompts", type=Path, nargs="+", required=True)
    ap.add_argument("--prompts-sums", type=Path, required=True)
    ap.add_argument("--workdirs", type=Path, nargs="+", required=True, help="every gen-* and recheck-* workdir")
    ap.add_argument("--train-receipts", type=Path, nargs="*", default=[])
    ap.add_argument("--leakcheck-receipts", type=Path, nargs="+", required=True)
    ap.add_argument("--records", type=Path, nargs="*", default=[], help="Phase 2 records of the variant's partitions")
    ap.add_argument("--recheck-sample", type=int, default=5, help="the N every recheck was queued with (genqueue)")
    ap.add_argument("--decision", type=Path, help="the variant's decision file (gencanary decide); required for every "
                                                  "variant but gen_canary")
    ap.add_argument("--dev-pilot-meta", type=Path, help="a second-round dev grid variant only: the "
                                                        "round's OWN dev_pilot_vN PROMPTS_META.json, to check that "
                                                        "every adapter was trained on it (compose, every key)")
    ap.add_argument("--lost-workdirs", type=Path, nargs="*", default=[], help="for the run manifest: a failed "
                                                                             "job's workdir, copied home into "
                                                                             "results-lost/ -- evidence only, never "
                                                                             "a source of scored output lines")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    if a.recheck_sample < 1:
        ap.error("--recheck-sample must be at least 1")
    if not a.records and a.variant != "gen_canary":
        print(f"REFUSED: --records is required for variant {a.variant!r}", file=sys.stderr)
        return 2
    if a.decision is None and a.variant != "gen_canary":
        print(f"REFUSED: --decision is required for variant {a.variant!r}.", file=sys.stderr)
        return 2

    parts = tuple(sorted(variant_spec(a.variant)))
    problems, meta = prompt_files(a.prompts, a.prompts_sums)
    problems += compose_problems(a.variant, meta["meta"]) + meta_files_problems(meta["meta"], a.prompts_sums)
    index, ids = {}, {p: set() for p in parts}
    for path in a.prompts:
        try:
            rows = read_jsonl(path, partitions=parts)
        except ValueError as e:
            problems.append(str(e))
            continue
        digest = sha256_file(path)
        for (rid, fmt), ex in rows.items():
            index[(ex.model, rid, fmt)] = (ex.partition, digest, prompt_sha256(ex.messages))
            ids[ex.partition].add(rid)
    listed = {}
    for model in sorted({r.model for p in parts for r in planned_runs(a.variant, p)}):
        found, listed[model] = read_excluded(a.prompts_sums, model)
        problems += [p for p in found if p not in problems]
    records = {}
    for path in a.records:
        try:
            rows = [json.loads(line) for line in jsonl_lines(path)]
            pairs = [(r["partition"], r["id"]) for r in rows]
        except (OSError, ValueError, TypeError, KeyError) as e:          # a missing file too
            problems.append(f"{path}: not a records file ({e!r})")
            continue
        for part, rid in pairs:
            records.setdefault(part, set()).add(rid)
    for p in parts:
        want = records.get(p, set())
        for rid in sorted(want - ids[p]):
            if not all((rid, f) in listed[m] for m in listed for f in ("F0", "F1", "F2")):
                problems.append(f"{p} record {rid} has no prompt and no exclusion")
        problems += [f"{p} prompt record {rid} is not a {p} record" for rid in sorted(ids[p] - want)]
    expected, excluded = {}, {}
    for p in parts:
        counts = Counter()
        for run in planned_runs(a.variant, p):
            for rid in sorted(ids[p]):
                if (rid, run.fmt) in listed[run.model]:
                    counts[listed[run.model][(rid, run.fmt)]] += 1
                elif (run.model, rid, run.fmt) not in index:
                    problems.append(f"{p} {rid} {run.fmt}: no {run.model} prompt and no exclusion")
                else:
                    expected[(rid, run.model, run.seed, run.condition, a.variant)] = (p, run.fmt)
        if counts:
            excluded[p] = dict(sorted(counts.items()))
    given = {w.resolve() for w in a.workdirs}
    ignored = [w for w in a.workdirs if w.name.endswith(".queue") and
               w.with_name(w.name[:-len(".queue")]).resolve() in given]
    queues = sorted(w.name for w in ignored)
    workdirs = [w for w in a.workdirs if w not in ignored]
    found, gens, rechecks, cross, code, composes = workdir_problems(workdirs, a.variant, a.recheck_sample)
    problems += found
    if a.decision is not None:
        problems += decision_problems(a.decision, a.variant, gens + rechecks)
    found, locks, first_run = lock_problems(gens + rechecks)
    problems += found
    want = meta["meta"].get("compose") if isinstance(meta["meta"], dict) else None
    problems += [f"{name}: compose {json.dumps(c, sort_keys=True)} is not the PROMPTS_META.json compose "
                 f"{json.dumps(want, sort_keys=True)} of --prompts-sums (one compose per variant)"
                 for name, c in sorted(composes.items()) if c != want]
    pilot_compose = None                       # the round's OWN dev_pilot_vN META compose
    if a.dev_pilot_meta is not None:
        pilot_compose = dev_pilot_compose(a.dev_pilot_meta)
        if pilot_compose is None:
            problems.append(f"--dev-pilot-meta {a.dev_pilot_meta}: no readable PROMPTS_META.json compose")
    found, adapters = train_digests(a.train_receipts, a.variant, meta["meta"], pilot_compose)
    problems += found
    # The training GPU per adapter, for the report; and its own two card-per-seed
    # checks (training card across models of one seed, and generation card across the conditions of one adapter).
    training_gpu = train_gpu_names(a.train_receipts)
    problems += train_card_problems(training_gpu) + gen_card_by_pair_problems(gens, rechecks)
    found, leaks = leak_receipts(a.leakcheck_receipts, code)
    problems += found
    seen, unexpected, mismatched = Counter(), set(), set()
    capped: dict = {}
    groups: dict = {}
    bad_adapter, bad_leak = set(), set()
    evidence: dict = {}           # for the run manifest: key -> the "ok" row's own line and producing workdir
    for w, rc in gens:
        # A non-DONE gen workdir given in --workdirs (already flagged "not DONE"
        # in `problems` above, by workdir_problems) contributes NO lines here -- its outputs.jsonl, even with
        # perfectly valid-looking lines (a job crashed mid-write, or was killed with a partial file), is not scored.
        # Its expected pairs fall through to `missing` and _missing_row() reads its receipt/attempts from
        # gens_by_pair (built below from every gen workdir, DONE or not), giving the right receipt_status --
        # never `ok`, which the procedure's own "chưa DONE" rule (GEN_RUNSHEET.md §6, lost pod) already requires.
        if rc.get("status") != "DONE":
            continue
        path = w / "outputs.jsonl"
        try:
            lines = jsonl_lines(path) if path.exists() else []
        except ValueError as e:                  # a torn multibyte tail, named, not a traceback
            problems.append(f"{w.name}/outputs.jsonl: {e}")
            continue
        for n, line in enumerate(lines, start=1):
            where = f"{w.name}/outputs.jsonl:{n}"
            try:
                row = json.loads(line)
            except ValueError:
                problems.append(f"{where}: not JSON")
                continue
            bad = row_problems(row)
            if bad:
                problems.append(f"{where}: {'; '.join(bad[:3])}")
                continue
            key = row_key(row)
            if key not in expected:
                unexpected.add(key)
                continue
            seen[key] += 1
            part, fmt = expected[key]
            if index[(row["model"], row["record_id"], fmt)][1:] != (row["prompts_sha256"], row["prompt_sha256"]):
                mismatched.add(key)
            if row["seed"] != "base" and adapters.get((row["model"], row["seed"])) != row["adapter_tensor_sha256"]:
                bad_adapter.add((row["model"], row["seed"]))
            leak = leaks.get(row["leakcheck_receipt_sha256"])
            if leak is None or leak.get("model") != row["model"]:
                bad_leak.add((row["model"], row["leakcheck_receipt_sha256"]))
            c = capped.setdefault(part, {}).setdefault(row["record_id"].split("|")[0], {}).setdefault(
                row["condition"], [0, 0])
            c[0] += row["finish_reason"] == "length"
            c[1] += 1
            g = groups.setdefault(part, {})
            label = "<=8192" if row["prompt_tokens"] <= LONG else ">8192"
            g[label] = g.get(label, 0) + 1
            evidence[key] = {"w": w, "rc": rc, "line": line}
    problems += [f"{m} {s}: adapter_tensor_sha256 is not the selected digest of its train receipt"
                 for m, s in sorted(bad_adapter)]
    problems += [f"{m}: leakcheck_receipt_sha256 {d[:12]}… is not among --leakcheck-receipts as a PASS receipt of {m}"
                 for m, d in sorted(bad_leak)]
    missing = set(expected) - set(seen)
    duplicates = {k for k, v in seen.items() if v > 1}
    by_run: dict = {}
    for key in expected:
        r = by_run.setdefault(f"{key[1]}/{key[2]}/{key[3]}", {"expected": 0, "found": 0})
        r["expected"] += 1
        r["found"] += seen[key] > 0
    ok = not (problems or missing or duplicates or unexpected or mismatched)
    # For the run manifest of 3C/3D: status_except_missing ignores ONLY the "missing" set, so RECHECK_MISMATCH
    # and every other problem (a generic workdir "not DONE" problem; recheck workdirs are never manifest rows) still
    # make it FAIL, exactly like status. By design, a non-DONE gen workdir given
    # in --workdirs (never --lost-workdirs, as the procedure requires) makes status_except_missing FAIL too: its
    # own "not DONE" problem lands in `problems`, on top of its pairs reading `missing`, not `ok` -- putting a
    # partial workdir in --workdirs at all, rather than --lost-workdirs, is itself the mistake this is meant to
    # surface, not something accepted_missing.jsonl should ever paper over.
    status_except_missing = not (problems or duplicates or unexpected or mismatched)
    gens_by_pair = {}
    for w, rc in gens:
        ident = rc.get("identity") if isinstance(rc.get("identity"), dict) else {}
        gens_by_pair[(ident.get("model"), ident.get("weights"))] = (w, rc)
    lost = lost_evidence(a.lost_workdirs, a.variant)
    manifest_path = a.out.parent / f"manifest.{a.variant}.jsonl"
    manifest_sha256 = write_manifest(manifest_path, a.variant, parts, ids, listed, index, gens_by_pair, lost, seen,
                                     evidence, adapters, decision_record(a.decision).get("decision_sha256"))
    report = {"variant": a.variant, "status": "PASS" if ok else "FAIL",
              "expected": {p: sum(v[0] == p for v in expected.values()) for p in parts}, "found": sum(seen.values()),
              "excluded": excluded, "missing": _listed(len(missing), missing),
              "duplicates": _listed(len(duplicates), duplicates), "unexpected": _listed(len(unexpected), unexpected),
              "mismatched": _listed(len(mismatched), mismatched), "by_run": dict(sorted(by_run.items())),
              "length_capped": capped, "prompt_length_groups": groups, "problems": problems[:200],
              "n_problems": len(problems), "problems_truncated": len(problems) > 200,
              "workdirs": {"gen": len(gens), "recheck": len(rechecks)}, "ignored_queue_dirs": queues,
              "locks": locks, "first_run_workdirs": first_run, **decision_record(a.decision),
              "cross_pod": cross, "outputs": {str(w / "outputs.jsonl"): rc.get("outputs_sha256") for w, rc in gens},
              # The basename, relative to coverage.json's
              # own directory -- not str(manifest_path), which was absolute in the tests/sample and relative to the
              # CWD (not to coverage.json) with the procedure's own --out; nothing downstream depended on the old
              # value (readers use --manifest plus manifest_sha256, never this field, to find the file).
              "manifest_path": manifest_path.name, "manifest_sha256": manifest_sha256,
              "status_except_missing": "PASS" if status_except_missing else "FAIL",
              # The training GPU of each adapter, for the report (card assignment is per
              # seed, decision 27/09; see train_card_problems for the cross-model-per-seed check).
              "training_gpu": {f"{m} {s}": gpu for (m, s), gpu in sorted(training_gpu.items())}}
    a.out.write_text(json.dumps(report, indent=2, sort_keys=True))
    print(json.dumps({k: report[k] for k in ("status", "expected", "found", "n_problems")}))
    return 0 if ok else 2


